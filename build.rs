//! Embeds the Python worker package and the example scripts into the binary,
//! so a release build is a single executable that only needs a Python
//! environment with CadQuery installed.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::{env, fs};

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let worker = root.join("worker").join("cq_worker");
    let examples = root.join("examples");

    let mut out = String::from("// @generated by build.rs\n\n");
    write_table(&mut out, "WORKER_FILES", &worker, "cq_worker/");
    write_table(&mut out, "EXAMPLES", &examples, "");

    let path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("embedded.rs");
    fs::write(path, out).unwrap();

    println!("cargo:rerun-if-changed=worker/cq_worker");
    println!("cargo:rerun-if-changed=examples");
}

/// Emits `pub const NAME: &[(&str, &str)]` with every `.py` file of `dir`,
/// sorted by file name, as (prefix + file name, contents).
fn write_table(out: &mut String, name: &str, dir: &Path, prefix: &str) {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|err| panic!("cannot read {}: {err}", dir.display()))
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "py"))
        .collect();
    files.sort();

    writeln!(out, "pub const {name}: &[(&str, &str)] = &[").unwrap();
    for file in files {
        let file_name = file.file_name().unwrap().to_string_lossy();
        writeln!(
            out,
            "    ({:?}, include_str!({:?})),",
            format!("{prefix}{file_name}"),
            file.display().to_string()
        )
        .unwrap();
        println!("cargo:rerun-if-changed={}", file.display());
    }
    writeln!(out, "];\n").unwrap();
}
